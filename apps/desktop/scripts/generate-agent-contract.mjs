import { readFileSync } from "node:fs";

const snapshot = new URL("../../../packages/contracts/p1/hub-openapi.json", import.meta.url);
const { paths, components } = JSON.parse(readFileSync(snapshot, "utf8"));
const endpoints = {
  AgentSummary: "/api/tasks/{task_id}/agent-summary",
  AgentRunDetail: "/api/tasks/{task_id}/agent-runs/{run_id}",
};
const refPrefix = "#/components/schemas/";
const referenced = new Set();

function render(schema) {
  if (schema.$ref?.startsWith(refPrefix)) {
    const name = schema.$ref.slice(refPrefix.length);
    referenced.add(name);
    return name;
  }
  if (schema.anyOf) return schema.anyOf.map(render).join(" | ");
  if (schema.enum) return schema.enum.map((value) => JSON.stringify(value)).join(" | ");
  if ("const" in schema) return JSON.stringify(schema.const);
  switch (schema.type) {
    case "object": {
      if (schema.additionalProperties !== false) break;
      const required = new Set(schema.required);
      const fields = Object.entries(schema.properties).map(([name, field]) =>
        `  ${JSON.stringify(name)}${required.has(name) ? "" : "?"}: ${render(field)};`);
      return ["{", ...fields, "}"].join("\n");
    }
    case "array": return `Array<${render(schema.items)}>`;
    case "integer":
    case "number": return "number";
    case "string":
    case "boolean":
    case "null": return schema.type;
  }
  throw new Error(`Unsupported Agent schema: ${schema.title ?? schema.type}`);
}

const definitions = Object.entries(endpoints).map(([name, path]) => {
  const schema = paths[path].get.responses["200"].content["application/json"].schema;
  return `export type ${name} = ${render(schema)};`;
});
// Rendering a model also adds its refs to the end of this Set.
for (const name of referenced) definitions.push(`type ${name} = ${render(components.schemas[name])};`);

const source = [
  "// Generated by apps/desktop/scripts/generate-agent-contract.mjs from packages/contracts/p1/hub-openapi.json.",
  ...definitions,
].join("\n\n") + "\n";

if (process.argv.includes("--check")) {
  const output = new URL("../src/agent-contract.generated.ts", import.meta.url);
  if (readFileSync(output, "utf8").replaceAll("\r\n", "\n") !== source) {
    throw new Error("Desktop Agent types are out of date with the Hub OpenAPI snapshot.");
  }
} else {
  process.stdout.write(source);
}
